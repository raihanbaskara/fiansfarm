-- 1. TABEL STOK INVENTARIS
create table if not exists public.stok_inventaris (
    id_produk text primary key,
    nama_produk text not null,
    stok_tersedia integer not null default 0,
    harga_per_butir integer not null default 2500,
    satuan text default 'butir',
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. TABEL RIWAYAT SENSOR CONVEYOR
create table if not exists public.riwayat_conveyor (
    id bigint generated by default as identity primary key,
    total_hitungan integer not null,
    delta integer not null default 1,
    status_mesin text default 'RUNNING',
    recorded_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. TABEL PESANAN & PENJUALAN (WEB / WHATSAPP / SHOPEE)
create table if not exists public.pesanan_penjualan (
    id_pesanan text primary key,
    nama_pemesan text,
    alamat text,
    jumlah_butir integer not null,
    total_biaya integer not null,
    sumber text default 'WhatsApp', -- 'WhatsApp', 'Web', 'Shopee'
    status text default 'Baru',     -- 'Baru', 'Diproses', 'Selesai'
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. TABEL LOG AKTIVITAS (AUDIT TRAIL PERUBAHAN STOK)
create table if not exists public.log_aktivitas (
    id bigint generated by default as identity primary key,
    product_id text default 'telur-ayam-kampung',
    delta integer not null,
    sumber text not null,          -- 'sensor', 'shopee', 'manual', 'wa'
    catatan text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ==============================================================================
-- KEAMANAN: ENABLE ROW LEVEL SECURITY (RLS) & IZINKAN AKSES PUBLIK / ANON
-- ==============================================================================
alter table public.stok_inventaris enable row level security;
alter table public.riwayat_conveyor enable row level security;
alter table public.pesanan_penjualan enable row level security;
alter table public.log_aktivitas enable row level security;

-- Policy untuk stok_inventaris
create policy "Izinkan publik baca stok" on public.stok_inventaris for select using (true);
create policy "Izinkan publik perbarui stok" on public.stok_inventaris for all using (true) with check (true);

-- Policy untuk riwayat_conveyor
create policy "Izinkan publik baca riwayat conveyor" on public.riwayat_conveyor for select using (true);
create policy "Izinkan publik catat conveyor" on public.riwayat_conveyor for all using (true) with check (true);

-- Policy untuk pesanan_penjualan
create policy "Izinkan publik baca pesanan" on public.pesanan_penjualan for select using (true);
create policy "Izinkan publik buat pesanan" on public.pesanan_penjualan for all using (true) with check (true);

-- Policy untuk log_aktivitas
create policy "Izinkan publik baca log aktivitas" on public.log_aktivitas for select using (true);
create policy "Izinkan publik tulis log aktivitas" on public.log_aktivitas for all using (true) with check (true);

-- ==============================================================================
-- AKTIFKAN REALTIME BROADCAST (SUPABASE REALTIME)
-- Agar saat telur lewat, layar web dan bot WA terupdate seketika
-- ==============================================================================
alter publication supabase_realtime add table public.stok_inventaris;
alter publication supabase_realtime add table public.riwayat_conveyor;
alter publication supabase_realtime add table public.log_aktivitas;

